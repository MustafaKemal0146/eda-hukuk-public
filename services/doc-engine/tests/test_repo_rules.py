def test_kk_p19a_15_models_are_generated_only() -> None:
    files = sorted(GENERATED.glob("*.py"))
    assert {f.name for f in files} >= {
        "docast_schema.py",
        "export_schema.py",
        "import_schema.py",
        "health_schema.py",
    }
    for f in files:
        assert f.read_text(encoding="utf-8").startswith("# generated by datamodel-codegen")
    hand_written = [
        str(p.relative_to(SERVICE))
        for p in SRC.rglob("*.py")
        if GENERATED not in p.parents and re.search(r"\(\s*BaseModel\s*\)", p.read_text("utf-8"))
    ]
    assert hand_written == []
    schemas = REPO / "packages" / "contracts" / "generated" / "json-schema"
    for name in ("export", "import", "docast"):
        assert (schemas / f"{name}.schema.json").is_file()


_FORBIDDEN_TOKENS = [
    "udf" + "_toolkit",
    "yargi" + "-sidecar",
    "yargi" + "_sidecar",
    "py" + "mupdf",
    "import " + "fitz",
    "from " + "fitz",
    "UYAP " + "uyumlu",
    "UYAP'a " + "gönderildi",
]
_GS_INSTALL = re.compile(r"(apt-get|apk|dnf|yum)[^\n]*\bghost" + "script", re.IGNORECASE)


def _scan_files() -> list[Path]:
    roots = [SERVICE / "src", SERVICE / "scripts", SERVICE / "tests"]
    files = [
        p
        for r in roots
        for p in r.rglob("*")
        if p.is_file() and p.suffix in (".py", ".json", ".toml", ".md", ".sh")
    ]
    files += [
        SERVICE / "pyproject.toml",
        SERVICE / "openapi.json",
        REPO / "uv.lock",
        REPO / "infra" / "docker" / "python-service.Dockerfile",
    ]
    return [f for f in files if f.name != Path(__file__).name]


def test_kk_p19a_16_clean_room_and_forbidden_components() -> None:
    hits = []
    for f in _scan_files():
        text = f.read_text(encoding="utf-8", errors="replace")
        folded = text.casefold()
        for token in _FORBIDDEN_TOKENS:
            if token.casefold() in folded:
                hits.append(f"{f.relative_to(REPO)}: {token}")
    assert hits == []
    lock = (REPO / "uv.lock").read_text(encoding="utf-8")
    banned = "|".join(["py" + "mupdf", "fi" + "tz", "ghost" + "script"])
    assert not re.search(rf'^name = "({banned})"', lock, re.MULTILINE)
    dockerfiles = [
        *(REPO / "infra" / "docker").glob("*.Dockerfile"),
        *(SERVICE / "scripts").glob("*.Dockerfile"),
    ]
    assert dockerfiles
    for f in dockerfiles:
        assert not _GS_INSTALL.search(f.read_text(encoding="utf-8")), f.name


